create table if not exists public.users (
    id bigint generated by default as identity primary key,
    auth_user_id uuid not null unique references auth.users(id) on delete cascade,
    name text not null,
    email text not null unique,
    is_verified boolean not null default false,
    last_sign_in_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

drop trigger if exists set_users_updated_at on public.users;

create trigger set_users_updated_at
before update on public.users
for each row
execute function public.set_updated_at();

create or replace function public.sync_auth_user_to_public_users()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    insert into public.users (
        auth_user_id,
        name,
        email,
        is_verified,
        last_sign_in_at
    )
    values (
        new.id,
        coalesce(
            new.raw_user_meta_data ->> 'name',
            new.raw_user_meta_data ->> 'username',
            new.raw_user_meta_data ->> 'full_name',
            split_part(new.email, '@', 1)
        ),
        new.email,
        coalesce(new.email_confirmed_at, new.confirmed_at) is not null
            or coalesce((new.raw_user_meta_data ->> 'email_verified')::boolean, false),
        new.last_sign_in_at
    )
    on conflict (auth_user_id)
    do update set
        name = coalesce(nullif(public.users.name, ''), excluded.name),
        email = excluded.email,
        is_verified = excluded.is_verified,
        last_sign_in_at = excluded.last_sign_in_at;

    return new;
end;
$$;

drop trigger if exists sync_auth_user_to_public_users on auth.users;

create trigger sync_auth_user_to_public_users
after insert or update of email, email_confirmed_at, confirmed_at, last_sign_in_at, raw_user_meta_data
on auth.users
for each row
execute function public.sync_auth_user_to_public_users();
